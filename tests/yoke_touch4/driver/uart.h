inline int uart_write_bytes(int,const void* ptr,size_t len) {
    const uint8_t* f=(const uint8_t*)ptr;sent.assign(f,f+len);
    assert(len==f[3]+6U && f[0]==0xAA && f[1]==0x55 && f[len-1]==0xEE);
    assert(crc(f+2,len-4)==f[len-2]);
    uint8_t cmd=f[2];std::vector<uint8_t> data;
    if(cmd==0x21)data={5,0x12,0x34,0xAB,0xCD,0,1,0xFF,0xFE};
    if(cmd==0x22)data={f[4]};
    if(cmd==0x23){assert(f[3]==8);data={1};}
    if(cmd==0x24)data={1};
    if(cmd==0x25)data.assign(cfgbytes,cfgbytes+8);
    if(cmd==0x26){assert(f[3]==9);data={(uint8_t)(1|(f[4]<<4))};}
    if(cmd==0x2F)data={0x10,1};
    auto response=packet(cmd-0x10,data);
    if(mode==1)response[response.size()-2]^=1;
    if(mode==2)response.back()=0;
    if(mode==3)response={0xAA,0x55,0x11,0x40};
    if(mode==4)response={0xAA,0x55,0x11,9,5};
    if(mode==5)response=packet(0x1F,{0x10,1});
    if(mode==6)enqueue({0,1,0xAA});
    if(mode==7)response=packet(0x11,{0,0,0,0,0,0,0,0,0});
    if(mode==8)response=packet(0x11,{0});
    if(mode!=9)enqueue(response);
    if(cmd==0x26)enqueue(packet(0x1F,{0x10,1}));
    return (int)len;
}
