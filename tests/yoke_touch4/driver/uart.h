inline uint8_t crc(const uint8_t* p, size_t len) {
    uint8_t c=0; for(size_t i=0;i<len;i++) c=crc_table[c^p[i]]; return c;
}
inline std::vector<uint8_t> packet(uint8_t cmd,std::vector<uint8_t> data) {
    std::vector<uint8_t> f={0xAA,0x55,cmd,(uint8_t)data.size()};
    f.insert(f.end(),data.begin(),data.end());
    f.push_back(crc(f.data()+2,f.size()-2)); f.push_back(0xEE); return f;
}
inline void enqueue(const std::vector<uint8_t>& data) {
    incoming.insert(incoming.end(),data.begin(),data.end());
}
